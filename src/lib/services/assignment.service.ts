"use client";

import type { Assignment, AssignmentStatus, Difficulty, Question } from "@/types";
import { sleep, uid } from "@/lib/utils";
import { PRACTICE_BANK } from "@/lib/mock-data/practice-bank";
import { topicName } from "@/lib/mock-data/curriculum";
import { getDB, setDB } from "./store";
import type { AssignmentFormValues } from "@/lib/validations/assignment";

const LATENCY = 450;

/** Derives the live status (e.g. overdue) for an assignment. */
export function liveStatus(a: Assignment, now = new Date()): AssignmentStatus {
  if (a.status === "submitted" || a.status === "evaluated") return a.status;
  if (new Date(a.dueDate).getTime() < now.getTime()) return "overdue";
  return a.status === "overdue" ? "pending" : a.status;
}

export async function listAssignments(): Promise<Assignment[]> {
  await sleep(LATENCY);
  return getDB().assignments;
}

export async function getAssignment(id: string): Promise<Assignment | undefined> {
  await sleep(LATENCY);
  return getDB().assignments.find((a) => a.id === id);
}

function toAssignment(values: AssignmentFormValues, base?: Assignment): Assignment {
  const questions: Question[] = values.questions.map((q, i) => ({
    id: base?.questions[i]?.id ?? uid("q"),
    number: i + 1,
    text: q.text,
    marks: q.marks,
    expectedAnswer: q.expectedAnswer,
  }));
  return {
    id: base?.id ?? uid("a"),
    title: values.title,
    subjectId: values.subjectId,
    topicId: values.topicId,
    grade: values.grade,
    description: values.description,
    instructions: values.instructions
      .split("\n")
      .map((l) => l.trim())
      .filter(Boolean),
    questions,
    maxMarks: questions.reduce((s, q) => s + q.marks, 0),
    difficulty: values.difficulty,
    estimatedMinutes: values.estimatedMinutes,
    dueDate: new Date(values.dueDate).toISOString(),
    createdAt: base?.createdAt ?? new Date().toISOString(),
    createdBy: base?.createdBy ?? "parent_1",
    source: values.source,
    markingScheme: values.markingScheme || undefined,
    referenceFileName: values.referenceFileName || undefined,
    status: base?.status ?? "pending",
    progress: base?.progress,
  };
}

export async function createAssignment(values: AssignmentFormValues): Promise<Assignment> {
  await sleep(LATENCY + 300);
  const a = toAssignment(values);
  setDB((db) => ({ ...db, assignments: [a, ...db.assignments] }));
  return a;
}

export async function updateAssignment(id: string, values: AssignmentFormValues): Promise<Assignment> {
  await sleep(LATENCY + 200);
  const existing = getDB().assignments.find((a) => a.id === id);
  if (!existing) throw new Error("Assignment not found");
  const updated = toAssignment(values, existing);
  setDB((db) => ({ ...db, assignments: db.assignments.map((a) => (a.id === id ? updated : a)) }));
  return updated;
}

export async function deleteAssignment(id: string): Promise<void> {
  await sleep(LATENCY);
  setDB((db) => ({ ...db, assignments: db.assignments.filter((a) => a.id !== id) }));
}

export function markAssignmentStarted(id: string) {
  setDB((db) => ({
    ...db,
    assignments: db.assignments.map((a) =>
      a.id === id && a.status === "pending" ? { ...a, status: "in_progress", progress: Math.max(a.progress ?? 0, 10) } : a,
    ),
  }));
}

/**
 * Simulated "AI" question generation. Phase 2: replace with a Gemini call.
 */
export async function generateAIQuestions(input: {
  topicId: string;
  difficulty: Difficulty;
  count: number;
  marksEach: number;
}): Promise<{ title: string; description: string; questions: { text: string; marks: number; expectedAnswer: string }[] }> {
  await sleep(1600);
  const order: Difficulty[] = [input.difficulty, "medium", "easy", "hard"];
  const pool = order.flatMap((d) => PRACTICE_BANK.filter((p) => p.topicId === input.topicId && p.difficulty === d));
  const unique = Array.from(new Map(pool.map((p) => [p.id, p])).values());
  const picked = unique.slice(0, input.count);
  return {
    title: `${topicName(input.topicId)} — ${input.difficulty[0].toUpperCase()}${input.difficulty.slice(1)} Practice`,
    description: `A ${input.difficulty} set of ${picked.length} questions on ${topicName(input.topicId)}, generated by Arth-QC AI (demo).`,
    questions: picked.map((p) => ({ text: p.text, marks: input.marksEach, expectedAnswer: p.answer })),
  };
}
