function step(description: string, awarded: number, max: number): StepMark {
  return { description, awarded, max, ok: awarded === max };
}

function result(
  assignmentId: string,
  n: number,
  studentAnswer: string,
  marksAwarded: number,
  status: ResultStatus,
  steps: StepMark[],
  errors: { kind: ErrorKind; description: string }[],
  explanation: string,
): QuestionResult {
  const a = seedAssignments().find((x) => x.id === assignmentId)!;
  const question = a.questions[n - 1];
  return {
    questionId: question.id,
    number: n,
    question: question.text,
    expectedAnswer: question.expectedAnswer,
    maxMarks: question.marks,
    studentAnswer,
    marksAwarded,
    status,
    steps,
    errors,
    explanation,
  };
}

